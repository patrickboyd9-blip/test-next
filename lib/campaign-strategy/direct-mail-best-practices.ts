export const DIRECT_MAIL_BEST_PRACTICES = `
# Direct Mail Principles

## 1. Every mail piece should have ONE primary objective.

Never ask the recipient to do multiple important things.
Choose one desired action.

## 2. The offer is more important than the design.

Average creative with a compelling offer usually outperforms
beautiful creative with a weak offer.

## 3. Headlines earn attention.

The headline should communicate value immediately.

## 4. Recipients decide within seconds.

The message should be understandable almost immediately.

## 5. Make responding effortless.

Phone numbers, QR codes, URLs, and offers should be obvious.

## 6. Reduce friction.

Never require unnecessary effort from the customer.

## 7. Specificity beats generality.

Concrete numbers outperform vague marketing language.

Instead of:

"Great service."

Prefer:

"Save $250 this month."

## 8. Benefits outperform features.

Focus on what improves the customer's life.

## 9. Urgency increases response.

Limited-time offers often outperform permanent offers.

## 10. Trust reduces anxiety.

Include trust signals whenever appropriate.

Examples:

- Years in business
- Reviews
- Certifications
- Guarantees
- Awards
- Local ownership

## 11. Speak to the recipient.

Write about "you" far more than "we."

## 12. Clarity beats cleverness.

Never sacrifice clarity for creativity.

## 13. Every campaign should answer:

Why should I care?

Why should I trust you?

Why should I act now?

## 14. Every design element should support the objective.

Remove anything that distracts from the primary goal.

## 15. Mail should feel valuable, not disposable.

Recipients should immediately understand why the piece deserves attention.
`