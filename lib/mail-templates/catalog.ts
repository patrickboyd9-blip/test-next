import type { CreativeSpec, ImageryKey, ImageryRole, LayoutVariant, LeadJob } from "@/lib/campaign-creator/types"

import type { MailTemplate, TemplateIndustry } from "./types"

interface MailerInput {
  id: string
  industry: TemplateIndustry
  name: string
  summary: string
  business: string
  headline: string
  subheadline: string
  body: string
  callToAction: string
  offer: string
  phone: string
  website: string
  layout: LayoutVariant
  tone: string
  palette: string[]
  visual: string
  imagery: ImageryKey
  leadJob: LeadJob
  imageryRole: ImageryRole
}

function mailer(input: MailerInput): MailTemplate {
  const spec: CreativeSpec = {
    layoutVariant: input.layout,
    headline: input.headline,
    subheadline: input.subheadline,
    body: input.body,
    callToAction: input.callToAction,
    offer: input.offer,
    phone: input.phone,
    website: input.website,
    qrDestination: input.website,
    visualDirection: input.visual,
    tone: input.tone,
    palette: input.palette,
    imagery: input.imagery,
    leadJob: input.leadJob,
    imageryRole: input.imageryRole,
    backLayout: "standard_address",
  }
  return {
    id: input.id,
    industry: input.industry,
    name: input.name,
    summary: input.summary,
    sampleBusinessName: input.business,
    size: "5x8",
    spec,
  }
}

