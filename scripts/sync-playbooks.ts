/**
 * Copies every Ad Psychologist industry playbook into the app.
 *   npx tsx scripts/sync-playbooks.ts [/path/to/ad-psych-library/industries]
 * Writes lib/design-intelligence/playbooks/<slug>.json (the fields the generator uses)
 * and regenerates lib/design-intelligence/playbooks/index.ts. No list is hard-coded:
 * a new playbook in the library is picked up on the next sync.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs"
import { join } from "node:path"

const SOURCE = process.argv[2] ?? "/workspace/ad-psych-library/industries"
const OUT = join(process.cwd(), "lib/design-intelligence/playbooks")
const KEEP = [
  "schema_version", "slug", "industry", "last_updated", "words_and_claims_to_avoid",
  "compliance_notes", "standing_rules", "emotion_by_offer", "emotion_by_offer_conflicts",
] as const

mkdirSync(OUT, { recursive: true })
for (const file of readdirSync(OUT)) if (file.endsWith(".json")) rmSync(join(OUT, file))

const slugs: string[] = []
for (const file of readdirSync(SOURCE).sort()) {
  if (!file.endsWith(".json") || file.startsWith("_")) continue
  const raw = JSON.parse(readFileSync(join(SOURCE, file), "utf8")) as Record<string, unknown>
  const slug = String(raw.slug ?? file.replace(/\.json$/, ""))
  if (!Array.isArray(raw.emotion_by_offer)) continue
  const slim: Record<string, unknown> = {}
  for (const key of KEEP) if (raw[key] !== undefined) slim[key] = raw[key]
  slim.slug = slug
  writeFileSync(join(OUT, `${slug}.json`), JSON.stringify(slim, null, 2) + "\n")
  slugs.push(slug)
}

const ident = (slug: string) => "pb_" + slug.replace(/[^a-z0-9]+/gi, "_")
const index = [
  "// Generated by scripts/sync-playbooks.ts. Do not edit by hand.",
  'import type { Playbook } from "../playbook-types"',
  "",
  ...slugs.map((slug) => `import ${ident(slug)} from "./${slug}.json"`),
  "",
  "export const PLAYBOOKS: Record<string, Playbook> = {",
  ...slugs.map((slug) => `  "${slug}": ${ident(slug)} as unknown as Playbook,`),
  "}",
  "",
].join("\n")
writeFileSync(join(OUT, "index.ts"), index)
console.log(`synced ${slugs.length} playbooks: ${slugs.join(", ")}`)
